 *     notes constantly.
 *
 * PHP `CP932` is NOT the fix: it disagrees with Go on 2262 code points rather
 * than 456, because it adds the Windows round-trip mappings Go deliberately
 * omits. Plain `SJIS` plus this table is the closest correct base.
