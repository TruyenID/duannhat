/**
 * plan-053 M5 (#1171) TR-34 — GENERATED. Do not hand-edit.
 *
 * PHP `mb_convert_encoding(..., "SJIS")` and Go `japanese.ShiftJIS` do not
 * agree on 456 code points, and the disagreement is invisible until a hash
 * fails:
 *
 *   - PHP encodes 9 that Go substitutes — ¢ £ ¥ ¬ ¯ ‖ ‾ − and 〜 (U+301C).
 *     〜 alone would be enough: Japanese opening hours are written "10:00〜22:00",
