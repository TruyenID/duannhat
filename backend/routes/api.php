// Platform is the sole identity and service-authorization boundary.
Route::prefix('v1')
    ->middleware(['sso.auth'])
    ->group(function () {
        // =====================================================================
        //  User Context (current user profile + paginated lookup endpoints)
        // =====================================================================
        Route::get('me/context', [UserContextController::class, 'context'])->name('api.v1.me.context');
