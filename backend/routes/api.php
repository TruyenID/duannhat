            Route::delete('/', [MeNotificationController::class, 'destroyAll'])
                ->middleware('throttle:5,1')
                ->name('api.v1.me.notifications.destroyAll');
            Route::patch('{notificationId}/seen', [MeNotificationController::class, 'seen'])->name('api.v1.me.notifications.seen');
            Route::patch('{notificationId}/read', [MeNotificationController::class, 'read'])->name('api.v1.me.notifications.read');
