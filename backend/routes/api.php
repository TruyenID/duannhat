// =========================================================================
//  POS-scoped — endpoints for pos-web (browser) and workstation (LAN).
//  Mounted under /api/v1/pos/...; shop context is resolved from the
//  X-Shop-Slug request header by ResolvePosShop so the URL shape is
//  identical regardless of whether the call lands on Cloud or on a
//  workstation's local HTTP server. Controllers are reused from
//  Api\V1\Shop\* — see routes/api/pos.php for the full route list.
//
//  Auth is COMPOUND (auth.sso_or_device): the SSO Sanctum token used by
//  admin-web works here, and so does the POS device token that pos-web
//  received from /api/v1/devices/pair. That's what lets pos-web fall
//  back from a downed workstation to the cloud API without re-auth.
//  The 'pos' rate limiter keys per-device (or per-user for SSO) so a
//  branch's terminals never share a bucket via NAT.
// =========================================================================
Route::prefix('v1')
    ->middleware(['auth.sso_or_device', 'throttle:pos'])
    ->group(function () {
        Route::prefix('pos')
            ->middleware([ResolvePosShop::class])
            ->name('api.v1.pos.')
            ->group(function () {
                require __DIR__.'/api/pos.php';
            });
    });
