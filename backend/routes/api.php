// =========================================================================
//  Public One-Click Email Unsubscribe (issue #173 part A — RFC 8058)
//
//  Auth: Laravel signed URL (HMAC over the URL, no DB token table). The
//  link is generated by NotificationMail and embedded in the
//  List-Unsubscribe / List-Unsubscribe-Post headers, so Gmail / Yahoo /
//  Apple Mail can post here directly from the inbox UI.
//
//  GET handles the human-clickable link; POST is the RFC 8058
//  one-click variant required by Gmail's Feb 2024 bulk-sender rules.
// =========================================================================
Route::middleware(['signed', 'throttle:30,1'])->group(function () {
    Route::get('v1/notifications/email/unsubscribe', EmailUnsubscribeController::class)
        ->name('api.v1.notifications.email.unsubscribe');
    Route::post('v1/notifications/email/unsubscribe', EmailUnsubscribeController::class)
        ->name('api.v1.notifications.email.unsubscribe.post');
});

// =========================================================================
