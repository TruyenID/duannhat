// ─── Metadata Types ──────────────────────────────────────────────────────────

type LocaleLabels = Record<string, string>;

/**
 * Describes a single field's metadata as generated by Omnify.
 *
 * @see `{entity}Metadata.fields` in `src/types/models/base/`
 */
export interface FieldMeta {
  /**
   * Field type taxonomy. Determines which UI component is rendered.
   *
   * | Type         | Component                        |
   * |--------------|----------------------------------|
   * | `string`     | `<Input>` or `<Input translatable>` |
   * | `text`       | `<Textarea>` or `<Textarea translatable>` |
   * | `number`     | `<Input type="number">`          |
   * | `boolean`    | `<Switch>` or `<Checkbox>`       |
   * | `enum`       | `<Select>`                       |
   * | `uuid`       | `<Combobox>` (relation) or `<Input>` |
   * | `date`       | `<Input type="date">`            |
   * | `datetime`   | `<Input type="datetime-local">`  |
   * | `file`       | `<FileUpload>`                   |
   * | `color`      | `<ColorPicker>`                  |
   * | `password`   | `<PasswordInput>`                |
   * | `rating`     | `<Rating>`                       |
   * | `slider`     | `<Slider>`                       |
   * | `checkbox`   | `<Checkbox>`                     |
   */
  type: "string" | "text" | "number" | "boolean" | "enum" | "uuid" | "date" | "datetime" | "file" | "color" | "password" | "rating" | "slider" | "checkbox" | (string & {});
  required: boolean;
  nullable: boolean;
  translatable: boolean;
  validation: {
    maxLength?: number;
    minLength?: number;
    min?: number;
    max?: number;
    pattern?: string;
    /** Max file size in bytes. For `type: "file"`. */
    maxSize?: number;
    /** Allowed MIME types. For `type: "file"`. */
    accept?: string;
    /** Max number of files. For `type: "file"`. */
    maxFiles?: number;
  };
  label: LocaleLabels;
  /** Per-locale placeholder text. Falls back to auto-derived from label if absent. */
  placeholder?: LocaleLabels;
  /** Per-locale description/help text shown below the input. */
  description?: LocaleLabels;
  enum?: string;
  enumValues?: string[];
  enumLabels?: Record<string, LocaleLabels>;
  relation?: {
    model: string;
    table?: string;
    onDelete?: string;
  };
}

/**
 * Entity-level metadata object as generated by Omnify.
 *
 * @example
 * ```ts
 * import { zoneMetadata } from "@/types/models/base/Zone";
 * <SchemaField metadata={zoneMetadata} field="name" ... />
 * ```
 */
export interface SchemaMetadata {
  modelName: string;
  fields: Record<string, FieldMeta>;
  translatableFields?: readonly string[];
  enumFields?: readonly string[];
  relationFields?: readonly string[];
}

export interface SchemaFieldOption {
  value: string;
  label: string;
  disabled?: boolean;
}

export interface SchemaFieldProps {
  /** Omnify-generated metadata object (e.g. `zoneMetadata`). */
  metadata: SchemaMetadata;
  /** Field key from `metadata.fields`. */
  field: string;
  /** Current field value. Type depends on `metadata.fields[field].type`. */
  value: unknown;
  /** Called when the value changes. */
  onChange: (value: unknown) => void;
  /**
   * Validation error(s).
   * - `string` — single error
   * - `string[]` — array (first displayed, Laravel 422 format)
   * - `Record<locale, string>` — per-locale errors for translatable fields
   */
  error?: string | string[] | Partial<Record<string, string>>;
  /** Options for enum or relation fields. Auto-generated from enumValues if not provided. */
  options?: SchemaFieldOption[];
  /** Override the auto-detected label. */
  label?: string;
  /** Override the auto-detected placeholder. */
  placeholder?: string;
  /** Override the auto-detected description. */
  description?: string;
  disabled?: boolean;
  readOnly?: boolean;
  size?: "xs" | "sm" | "default" | "lg" | "xl";
  className?: string;
  /** Hide the label. */
  hideLabel?: boolean;
  /** Hide the description. */
  hideDescription?: boolean;
  /**
   * Render boolean as checkbox instead of switch.
   * Only applies when `type === "boolean"`.
   */
  asCheckbox?: boolean;
  /** FileUpload variant. Only applies when `type === "file"`. */
  fileVariant?: "dropzone" | "compact" | "avatar" | "gallery" | "inline";
}

// ─── Helpers ─────────────────────────────────────────────────────────────────

const PLACEHOLDER_PREFIX: Record<string, string> = {
  ja: "を入力",
  en: "Enter ",
  vi: "Nhập ",
};

function resolveLabel(labels: LocaleLabels | undefined, locale: string, fallback: string): string {
  if (!labels || Object.keys(labels).length === 0) return fallback;
  return labels[locale] ?? labels["en"] ?? Object.values(labels)[0] ?? fallback;
}

/**
 * Resolve placeholder per locale. For translatable fields, returns a map
 * so each locale tab gets its own placeholder.
 */
function resolvePlaceholderForLocale(fieldMeta: FieldMeta, locale: string, label: string): string {
  const explicit = fieldMeta.placeholder?.[locale] ?? fieldMeta.placeholder?.["en"];
  if (explicit) return explicit;
  if (locale === "ja") return `${resolveLabel(fieldMeta.label, locale, label)}${PLACEHOLDER_PREFIX.ja}`;
  const prefix = PLACEHOLDER_PREFIX[locale] ?? PLACEHOLDER_PREFIX.en;
  return `${prefix}${resolveLabel(fieldMeta.label, locale, label)}`;
}

function derivePlaceholder(label: string, locale: string): string {
  if (locale === "ja") return `${label}${PLACEHOLDER_PREFIX.ja}`;
  const prefix = PLACEHOLDER_PREFIX[locale] ?? PLACEHOLDER_PREFIX.en;
  return `${prefix}${label}`;
}

function humanize(field: string): string {
  return field.replace(/_/g, " ").replace(/^./, (c) => c.toUpperCase());
}

const IS_DEV = process.env.NODE_ENV !== "production";

function devWarn(message: string): void {
  if (IS_DEV) console.warn(`[SchemaField] ${message}`);
}

type TranslatableValue = Record<string, string>;

function normalizeTranslatableValue(value: unknown, defaultLocale: string): TranslatableValue {
  if (value && typeof value === "object" && !Array.isArray(value)) {
    return value as TranslatableValue;
  }
  if (typeof value === "string") {
    devWarn(
      `Translatable field received a plain string value instead of Record<Locale, string>. ` +
      `Auto-wrapping as { "${defaultLocale}": "${value.slice(0, 30)}..." }.`,
    );
    return { [defaultLocale]: value };
  }
  return {};
}

// ─── Component ───────────────────────────────────────────────────────────────

/**
 * Metadata-driven form field that reads Omnify-generated `{entity}Metadata` and
 * automatically renders the correct input component with proper label,
 * placeholder, validation, and error display.
 *
 * ## Type → Component mapping
 *
 * | `type`       | `translatable` | Component                          |
 * |--------------|----------------|------------------------------------|
 * | `string`     | `false`        | `<Input>`                          |
 * | `string`     | `true`         | `<Input translatable>`             |
 * | `text`       | `false`        | `<Textarea>`                       |
 * | `text`       | `true`         | `<Textarea translatable>`          |
 * | `number`     | —              | `<Input type="number">`            |
 * | `boolean`    | —              | `<Switch>` (or `<Checkbox>` with `asCheckbox`) |
 * | `checkbox`   | —              | `<Checkbox>`                       |
 * | `enum`       | —              | `<Select>`                         |
 * | `uuid`       | —              | `<Combobox>` (needs `options`)     |
 * | `date`       | —              | `<Input type="date">`              |
 * | `datetime`   | —              | `<Input type="datetime-local">`    |
 * | `file`       | —              | `<FileUpload>`                     |
 * | `color`      | —              | `<ColorPicker>`                    |
 * | `password`   | —              | `<PasswordInput>`                  |
 * | `rating`     | —              | `<Rating>`                         |
 * | `slider`     | —              | `<Slider>`                         |
 * | _(other)_    | —              | `<Input>` (fallback)               |
 *
 * ## Translatable placeholder
 *
 * When a field is `translatable: true`, the placeholder changes per active
 * locale tab. Each locale gets its own placeholder derived from
 * `metadata.placeholder[locale]` or auto-generated from `label[locale]`.
 *
 * @example
 * ```tsx
 * <SchemaField metadata={zoneMetadata} field="name" value={form.name} onChange={v => update("name", v)} />
 * ```
 */
function SchemaField({
  metadata,
  field,
  value,
  onChange,
  error,
  options: optionsProp,
  label: labelOverride,
  placeholder: placeholderOverride,
  description: descriptionOverride,
  disabled,
  readOnly,
  size,
  className,
  hideLabel,
  hideDescription,
  asCheckbox,
  fileVariant,
}: SchemaFieldProps) {
  const { currentLocale } = useLocale();

  if (!metadata) {
    devWarn("metadata prop is undefined or null.");
    return null;
  }

  const fieldMeta = metadata.fields[field];
  if (!fieldMeta) {
    devWarn(
      `Field "${field}" not found in metadata for "${metadata.modelName}". ` +
      `Available: ${Object.keys(metadata.fields).join(", ")}.`,
    );
    return null;
  }

  const resolvedLabel = labelOverride ?? resolveLabel(fieldMeta.label, currentLocale, humanize(field));
  const resolvedPlaceholder = placeholderOverride ??
    (resolveLabel(fieldMeta.placeholder, currentLocale, "") ||
    (fieldMeta.type !== "boolean" && fieldMeta.type !== "checkbox" ? derivePlaceholder(resolvedLabel, currentLocale) : ""));
  const resolvedDescription = descriptionOverride ?? resolveLabel(fieldMeta.description, currentLocale, "");

  let errorMessage: string | undefined;
  let translatableErrors: Partial<Record<string, string>> | undefined;

  if (typeof error === "string") {
    errorMessage = error;
  } else if (Array.isArray(error)) {
    errorMessage = error[0];
  } else if (error && typeof error === "object") {
    translatableErrors = error;
    if (!fieldMeta.translatable) {
      errorMessage = Object.values(error).find(Boolean);
    }
  }

  const hasError = !!(errorMessage || (translatableErrors && Object.values(translatableErrors).some(Boolean)));
  const fieldId = `schema-field-${metadata.modelName}-${field}`;

  let inputElement: React.ReactNode;

  switch (fieldMeta.type) {
    // ── Boolean → Switch or Checkbox ──────────────────────────────────
    case "boolean": {
      const checked = typeof value === "boolean" ? value : !!value;
      if (asCheckbox) {
        inputElement = (
          <div className="flex items-center gap-2">
            <Checkbox id={fieldId} checked={checked} onCheckedChange={(v) => onChange(v === true)} disabled={disabled} aria-invalid={hasError || undefined} />
            {!hideLabel && <Label htmlFor={fieldId} className="text-sm font-normal cursor-pointer">{resolvedLabel}</Label>}
          </div>
        );
      } else {
        inputElement = (
          <div className="flex items-center gap-3">
            <Switch id={fieldId} checked={checked} onCheckedChange={(v) => onChange(v)} disabled={disabled} aria-invalid={hasError || undefined} />
            {!hideLabel && <Label htmlFor={fieldId} className="text-sm font-normal cursor-pointer">{resolvedLabel}</Label>}
          </div>
        );
      }
      return (
        <div data-slot="schema-field" data-field={field} data-type="boolean" className={cn("flex flex-col gap-1", className)}>
          {inputElement}
          {!hideDescription && resolvedDescription && <p className="text-xs text-muted-foreground">{resolvedDescription}</p>}
          {errorMessage && <p className="text-xs text-destructive">{errorMessage}</p>}
        </div>
      );
    }

    // ── Checkbox (explicit type) ──────────────────────────────────────
    case "checkbox": {
      const checked = typeof value === "boolean" ? value : !!value;
      inputElement = (
        <div className="flex items-center gap-2">
          <Checkbox id={fieldId} checked={checked} onCheckedChange={(v) => onChange(v === true)} disabled={disabled} aria-invalid={hasError || undefined} />
          {!hideLabel && <Label htmlFor={fieldId} className="text-sm font-normal cursor-pointer">{resolvedLabel}</Label>}
        </div>
      );
      return (
        <div data-slot="schema-field" data-field={field} data-type="checkbox" className={cn("flex flex-col gap-1", className)}>
          {inputElement}
          {!hideDescription && resolvedDescription && <p className="text-xs text-muted-foreground">{resolvedDescription}</p>}
          {errorMessage && <p className="text-xs text-destructive">{errorMessage}</p>}
        </div>
      );
    }

    // ── Enum → Select ─────────────────────────────────────────────────
    case "enum": {
      const enumValues = fieldMeta.enumValues ?? [];
      if (enumValues.length === 0) devWarn(`Field "${field}" has type "enum" but no enumValues in metadata for "${metadata.modelName}".`);
      const enumOptions: SchemaFieldOption[] = optionsProp ?? enumValues.map((v) => ({
        value: v,
        label: fieldMeta.enumLabels ? resolveLabel(fieldMeta.enumLabels[v], currentLocale, v) : v,
      }));
      inputElement = (
        <Select value={typeof value === "string" ? value : ""} onValueChange={(v) => onChange(v)} disabled={disabled}>
          <SelectTrigger id={fieldId} aria-invalid={hasError || undefined}>
            <SelectValue placeholder={resolvedPlaceholder} />
          </SelectTrigger>
          <SelectContent>
            {enumOptions.map((opt) => (
              <SelectItem key={opt.value} value={opt.value} disabled={opt.disabled}>{opt.label}</SelectItem>
            ))}
          </SelectContent>
        </Select>
      );
      break;
    }

    // ── Relation (FK) → Combobox ──────────────────────────────────────
    case "uuid": {
      if (fieldMeta.relation) {
        const comboboxOptions: ComboboxOption[] = optionsProp ?? [];
        if (!optionsProp) devWarn(`Field "${field}" is a relation to "${fieldMeta.relation.model}" but no "options" prop provided.`);
        inputElement = (
          <Combobox
            options={comboboxOptions}
            value={typeof value === "string" ? value : ""}
            onChange={(v) => onChange(v)}
            placeholder={resolvedPlaceholder}
            disabled={disabled || (!optionsProp && comboboxOptions.length === 0)}
          />
        );
      } else {
        inputElement = <Input id={fieldId} value={typeof value === "string" ? value : ""} onChange={(e) => onChange(e.target.value)} placeholder={resolvedPlaceholder} disabled={disabled} readOnly={readOnly} size={size} aria-invalid={hasError || undefined} />;
      }
      break;
    }

    // ── Number ────────────────────────────────────────────────────────
    case "number": {
      const numValue = typeof value === "number" ? value : (typeof value === "string" ? value : "");
      inputElement = (
        <Input id={fieldId} type="number" value={String(numValue)} onChange={(e) => { const raw = e.target.value; onChange(raw === "" ? "" : Number(raw)); }} placeholder={resolvedPlaceholder} min={fieldMeta.validation.min} max={fieldMeta.validation.max} disabled={disabled} readOnly={readOnly} size={size} aria-invalid={hasError || undefined} />
      );
      break;
    }

    // ── Date / Datetime ───────────────────────────────────────────────
    case "date": {
      inputElement = <Input id={fieldId} type="date" value={typeof value === "string" ? value : ""} onChange={(e) => onChange(e.target.value)} disabled={disabled} readOnly={readOnly} size={size} aria-invalid={hasError || undefined} />;
      break;
    }
    case "datetime": {
      inputElement = <Input id={fieldId} type="datetime-local" value={typeof value === "string" ? value : ""} onChange={(e) => onChange(e.target.value)} disabled={disabled} readOnly={readOnly} size={size} aria-invalid={hasError || undefined} />;
      break;
    }

    // ── File Upload ───────────────────────────────────────────────────
    case "file": {
      const files = Array.isArray(value) ? value as File[] : [];
      inputElement = (
        <FileUpload
          value={files}
          onChange={(f) => onChange(f)}
          accept={fieldMeta.validation.accept}
          maxSize={fieldMeta.validation.maxSize}
          maxFiles={fieldMeta.validation.maxFiles}
          multiple={(fieldMeta.validation.maxFiles ?? 1) > 1}
          disabled={disabled}
          variant={fileVariant}
          placeholder={resolvedPlaceholder}
        />
      );
      break;
    }

    // ── Color Picker ──────────────────────────────────────────────────
    case "color": {
      inputElement = (
        <ColorPicker
          value={typeof value === "string" ? value : "#000000"}
          onChange={(c) => onChange(c)}
          disabled={disabled}
        />
      );
      break;
    }

    // ── Password ──────────────────────────────────────────────────────
    case "password": {
      inputElement = (
        <PasswordInput
          id={fieldId}
          value={typeof value === "string" ? value : ""}
          onChange={(e) => onChange(e.target.value)}
          placeholder={resolvedPlaceholder}
          disabled={disabled}
          readOnly={readOnly}
          size={size}
          aria-invalid={hasError || undefined}
        />
      );
      break;
    }

    // ── Rating ────────────────────────────────────────────────────────
    case "rating": {
      inputElement = (
        <Rating
          value={typeof value === "number" ? value : 0}
          onChange={(v) => onChange(v)}
          max={fieldMeta.validation.max ?? 5}
          readonly={disabled || readOnly}
        />
      );
      break;
    }

    // ── Slider ────────────────────────────────────────────────────────
    case "slider": {
      const sliderValue = typeof value === "number" ? value : 0;
      inputElement = (
        <Slider
          value={[sliderValue]}
          onValueChange={(v) => onChange(v[0])}
          min={fieldMeta.validation.min ?? 0}
          max={fieldMeta.validation.max ?? 100}
          disabled={disabled}
        />
      );
      break;
    }

    // ── Text → Textarea ───────────────────────────────────────────────
    case "text": {
      if (fieldMeta.translatable) {
        const tv = normalizeTranslatableValue(value, currentLocale);
        inputElement = <Textarea id={fieldId} translatable value={tv} onChange={(v) => onChange(v)} placeholder={resolvePlaceholderForLocale(fieldMeta, currentLocale, resolvedLabel)} maxLength={fieldMeta.validation.maxLength} disabled={disabled} readOnly={readOnly} errors={translatableErrors} aria-invalid={hasError || undefined} />;
      } else {
        inputElement = <Textarea id={fieldId} value={typeof value === "string" ? value : ""} onChange={(e) => onChange(e.target.value)} placeholder={resolvedPlaceholder} maxLength={fieldMeta.validation.maxLength} disabled={disabled} readOnly={readOnly} aria-invalid={hasError || undefined} />;
      }
      break;
    }

    // ── String (default) → Input ──────────────────────────────────────
    case "string":
    default: {
      if (fieldMeta.type !== "string" && fieldMeta.type !== undefined) {
        devWarn(`Unknown field type "${fieldMeta.type}" for "${field}" in "${metadata.modelName}". Falling back to <Input>.`);
      }
      if (fieldMeta.translatable) {
        const tv = normalizeTranslatableValue(value, currentLocale);
        inputElement = <Input id={fieldId} translatable value={tv} onChange={(v) => onChange(v)} placeholder={resolvePlaceholderForLocale(fieldMeta, currentLocale, resolvedLabel)} maxLength={fieldMeta.validation.maxLength} disabled={disabled} readOnly={readOnly} size={size} errors={translatableErrors} aria-invalid={hasError || undefined} />;
      } else {
        inputElement = <Input id={fieldId} value={typeof value === "string" ? value : String(value ?? "")} onChange={(e) => onChange(e.target.value)} placeholder={resolvedPlaceholder} maxLength={fieldMeta.validation.maxLength} disabled={disabled} readOnly={readOnly} size={size} aria-invalid={hasError || undefined} />;
      }
      break;
    }
  }

  return (
    <div data-slot="schema-field" data-field={field} data-type={fieldMeta.type} data-translatable={fieldMeta.translatable || undefined} className={cn("flex flex-col gap-1.5", className)}>
      {!hideLabel && (
        <Label htmlFor={fieldId} className={cn(hasError && "text-destructive")}>
          {resolvedLabel}
          {fieldMeta.required && <span className="text-destructive ml-0.5">*</span>}
        </Label>
      )}
      {inputElement}
      {!hideDescription && resolvedDescription && <p className="text-xs text-muted-foreground">{resolvedDescription}</p>}
      {errorMessage && !fieldMeta.translatable && <p className="text-xs text-destructive">{errorMessage}</p>}
    </div>
  );
}

SchemaField.displayName = "SchemaField";

export { SchemaField };
