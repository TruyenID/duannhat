interface FieldErrors {
  [field: string]: string[];
}

// A fully Japanese product name slugifies to "" \u2014 see @/lib/option-slug for the
// fallback. `autoSlug` is the derive-from-name path (never empty); `slugify` is
// the hand-edit path, which must leave a half-typed value alone.
function autoSlug(raw: string): string {
  return toResourceSlug(raw, "product");
}

function slugify(raw: string): string {
  return slugifyHyphen(raw);
}

export default function NewProductPage() {
  const router = useRouter();
  const params = useParams<{ brandSlug: string }>();
  const brandSlug = params.brandSlug;
  const { t } = useTranslation();

  // -- Form state ----------------------------------------------------------
  // Translatable fields hold one value per locale; the default-locale value
  // (ja) gets sent at the top level of the request body and the per-locale
  // dicts are sent under their own keys (`ja`/`en`/`vi`).
  const [name, setName] = useState<TranslatableValue>(emptyLocaleMap);
  const [slug, setSlug] = useState("");
  const [slugTouched, setSlugTouched] = useState(false);
  const [description, setDescription] = useState<TranslatableValue>(emptyLocaleMap);
  const [productTypeId, setProductTypeId] = useState("");
  // Status is fixed at "draft" on create — backend rejects anything else.
  // Post-save, the user moves the product through the approval workflow
  // (submit → pending → approve → approved → activate) from the detail page.
  const status: ProductStatus = "draft";
  const [isHidden, setIsHidden] = useState(false);
  const [categoryIds, setCategoryIds] = useState<string[]>([]);
  const [taxTypeId, setTaxTypeId] = useState<string | null>(null);
  // A combo, in this product model, is just "a product with topping groups
  // attached". There is no separate combo entity — product_type.code = 'combo'
  // is only a label for filtering. So the form shows variants + topping groups
  // side by side and lets each toggle independently. A burger with size M/L
  // (variants) plus add-on toppings (groups) is a perfectly valid product.
  const [hasVariants, setHasVariants] = useState(false);

  const [baseSku, setBaseSku] = useState("");
  const [basePrice, setBasePrice] = useState("");

  const [options, setOptions] = useState<DraftOption[]>([]);
  const [skus, setSkus] = useState<DraftSku[]>([]);
  const [fieldErrors, setFieldErrors] = useState<FieldErrors>({});
  // Gallery runs in staged mode on the create page — uploads create temp
  // Files on the backend, but nothing is attached until the product is
  // actually saved (at which point the UUID list is sent as gallery_file_ids).
  const [galleryImages, setGalleryImages] = useState<ProductImageFile[]>([]);
  // Unsaved-changes guard: dialog opens when user tries to leave with dirty
  // state (via the Cancel button / handleRequestExit).
  const [confirmExitOpen, setConfirmExitOpen] = useState(false);

  // -- Lookups -------------------------------------------------------------
  // Hooks thread `locale` into the queryKey so a language switch invalidates
  // the cache and refetches translated labels. Bypassing them with an inline
  // useQuery (ex-queryKey w/o locale) caused sidebar labels to stay stale.
  const productTypes = useProductTypeLookup(brandSlug);
  const categories = useCategoryLookup(brandSlug);
  const taxTypes = useTaxTypeLookup(brandSlug);
  const toppingGroups = useToppingGroupLookup(brandSlug);

  const create = useCreateProductWithOptions(brandSlug);

  // Topping group ids attached to the product. After save we flush these via
  // toppingGroupService.syncForProduct(...). An empty list is fine — most
  // products won't have any.
  const [toppingGroupIds, setToppingGroupIds] = useState<string[]>([]);

  // Resolve the "effective" product name: prefer the canonical default locale
  // (ja), but fall back to whichever locale the user actually filled in.
  // This avoids the silent-disable trap when the app UI locale differs from
  // DEFAULT_LOCALE (e.g. user is in VI → TranslatableField opens VI tab
  // first → JA stays empty → button was disabled with no explanation).
  const effectiveName = useMemo(() => {
    const preferred = name[DEFAULT_LOCALE]?.trim();
    if (preferred) return preferred;
    return (
      Object.values(name)
        .find((v) => v?.trim())
        ?.trim() ?? ""
    );
  }, [name]);

  // Auto-slug from the effective name — tracks name as user types, until
  // the user manually edits the slug input (then it stays put).
  useEffect(() => {
    if (slugTouched) return;
    setSlug(effectiveName ? autoSlug(effectiveName) : "");
  }, [effectiveName, slugTouched]);

  // -- Derived -------------------------------------------------------------
  const validOptionsForSubmit = useMemo(
    () =>
      options
        .map((o) => ({ ...o, values: o.values.filter((v) => v.label.trim() !== "") }))
        .filter((o) => o.values.length > 0 && o.name.trim() !== ""),
    [options]
  );

  // Every selected variant must have a price before the product can be saved.
  // The entered value is the SELLING price; empty string, negative, or
  // non-numeric values count as "missing" and are blocked at the form layer.
  // 0 IS a valid price (free item / giveaway).
  const selectedSkus = useMemo(() => skus.filter((s) => s.selected), [skus]);
  const missingPriceCount = useMemo(
    () => selectedSkus.filter((s) => !isValidRequiredPrice(s.costPrice)).length,
    [selectedSkus]
  );

  // Non-variant flow auto-creates a default SKU on the backend. The entered
  // value is the SELLING price (selling_price is NOT NULL on product_skus), so
  // the form requires a value before the request leaves the browser — 0 is
  // allowed, only empty/negative is not. Without this guard the server returns
  // a raw SQLSTATE 23000 toast.
  const basePriceValid = hasVariants || isValidRequiredPrice(basePrice);

  const canSubmit =
    effectiveName.length > 0 &&
    productTypeId !== "" &&
    !create.isPending &&
    basePriceValid &&
    (!hasVariants ||
      (validOptionsForSubmit.length > 0 && selectedSkus.length > 0 && missingPriceCount === 0));

  // Dirty-state: any user input on the form counts as unsaved changes.
  // Matches the guard used on the menu items page — prevents accidental
  // navigation loss on the create flow.
  const hasChanges = useMemo(() => {
    const anyLocaleFilled = (v: TranslatableValue) => Object.values(v).some((s) => s?.trim());
    return (
      anyLocaleFilled(name) ||
      anyLocaleFilled(description) ||
      slug.trim() !== "" ||
      productTypeId !== "" ||
      isHidden ||
      categoryIds.length > 0 ||
      hasVariants ||
      baseSku.trim() !== "" ||
      basePrice.trim() !== "" ||
      options.length > 0 ||
      skus.length > 0 ||
      toppingGroupIds.length > 0
    );
  }, [
    name,
    description,
    slug,
    productTypeId,
    isHidden,
    categoryIds,
    hasVariants,
    baseSku,
    basePrice,
    options,
    skus,
    toppingGroupIds,
  ]);

  const handleRequestExit = useCallback(() => {
    if (hasChanges) {
      setConfirmExitOpen(true);
      return;
    }
    router.push(`/hq/${brandSlug}/products`);
  }, [hasChanges, router, brandSlug]);

  // Browser-level guard: prompt native confirmation when user tries to
  // refresh / close the tab / navigate to an external URL while the form
  // has enough data to be saved (submit button enabled). Chosen condition
  // is `canSubmit` rather than `hasChanges` — we only want to warn when the
  // user is about to lose *savable* work, not partial scribbles.
  useEffect(() => {
    if (!canSubmit || create.isPending) return;
    const handler = (e: BeforeUnloadEvent) => {
      e.preventDefault();
      // Legacy Chrome/Edge: returnValue must be set to trigger the prompt.
      e.returnValue = "";
    };
    window.addEventListener("beforeunload", handler);
    return () => window.removeEventListener("beforeunload", handler);
  }, [canSubmit, create.isPending]);

  // -- Submit --------------------------------------------------------------
  async function handleSubmit() {
    setFieldErrors({});

    // Defence in depth — Save is already disabled when basePrice is missing,
    // but if a future entry point triggers handleSubmit directly we still
    // want a friendly inline error instead of the raw SQL toast (selling_price
    // is NOT NULL on product_skus).
    if (!hasVariants && !isValidRequiredPrice(basePrice)) {
      setFieldErrors({ base_price: [t("hq.products.basic_info.cost_price_required")] });
      return;
    }

    // Mirror the same filter that sku-preview-table uses so value_indices stay aligned.
    const payloadOptions = hasVariants
      ? options
          .map((o) => ({
            ...o,
            values: o.values.filter((v) => v.label.trim() !== ""),
          }))
          .filter((o) => o.values.length > 0 && o.name.trim() !== "")
      : [];

    // Build locale overrides then drop any locale whose `name` is empty.
    // product_translations.name is NOT NULL and Laravel's
    // ConvertEmptyStringsToNull middleware turns "" → null, so sending an
    // empty name triggers an integrity constraint violation.
    const i18nPayload = buildI18nPayload({
      name,
      description,
    });
    for (const locale of Object.keys(i18nPayload)) {
      if (!i18nPayload[locale as keyof typeof i18nPayload]?.name?.trim()) {
        delete i18nPayload[locale as keyof typeof i18nPayload];
      }
    }

    const effectiveDescription =
      description[DEFAULT_LOCALE]?.trim() ||
      Object.values(description)
        .find((v) => v?.trim())
        ?.trim() ||
      "";

    const payload: CreateProductWithOptionsInput = {
      // effectiveName (not name[DEFAULT_LOCALE]) so the top-level mirror matches
      // canSubmit's fallback: a VN user filling only en/vi (ja empty) must not
      // send name:"" → NOT NULL violation. Mirrors the description fallback below.
      name: effectiveName,
      product_type_id: productTypeId,
      slug: slug.trim() || null,
      description: effectiveDescription || null,
      status,
      is_hidden: isHidden,
      // plan-043 — null = inherit brand default.
      tax_type_id: taxTypeId,
      category_ids: categoryIds,
      gallery_file_ids: galleryImages.map((img) => img.id),
      // Locale overrides — sent under `ja`/`en`/`vi` keys per backend rules.
      ...i18nPayload,
      options: payloadOptions.map((o, idx) => ({
        key: o.key,
        name: o.name,
        position: (idx + 1) as 1 | 2 | 3,
        is_active: true,
        values: o.values.map((v, i) => ({
          value: v.value,
          label: v.label,
          position: i + 1,
          is_active: true,
        })),
      })),
      skus: hasVariants
        ? skus
            .filter((s) => s.selected)
            .map((s) => ({
              value_indices: s.valueIndices,
              // The operator enters the SELLING price (shown on menus). cost_price
              // defaults to 0 and is auto-computed later from recipe/material;
              // is_cost_override=false keeps the SKU in auto mode (issue #875).
              // parseOptionalPrice, not `x ? Number(x) : null` — the ternary is
              // the same falsy-zero trap the guards above avoid, and it only
              // survives today because "0" is a truthy STRING.
              selling_price: parseOptionalPrice(s.costPrice),
              cost_price: 0,
              is_cost_override: false,
              is_active: true,
            }))
        : [
            {
              value_indices: [],
              sku: baseSku || null,
              selling_price: parseOptionalPrice(basePrice),
              cost_price: 0,
              is_cost_override: false,
              is_active: true,
            },
          ],
    };

    try {
      const result = await create.mutateAsync(payload);

      // Sync the picked topping groups against the freshly-created product.
      // A product without any topping groups is the common case (skipped). If
      // sync fails the product is already saved — surface a toast and still
      // navigate to the detail page so the user can retry there (the existing
      // ProductToppingGroupsCard handles the same sync).
      if (toppingGroupIds.length > 0) {
        try {
          await toppingGroupService.syncForProduct(brandSlug, result.data.id, {
            topping_group_ids: toppingGroupIds,
          });
        } catch (syncErr) {
          console.error(">>> [ERROR] Sync topping groups failed:", syncErr);
          toast.error(t("hq.products.combo.sync_failed"));
        }
      }

      router.push(`/hq/${brandSlug}/products/${result.data.id}`);
    } catch (err: unknown) {
      // DEBUG: Log detailed error info
      if (err instanceof ApiError) {
        console.error(">>> [ERROR] Create Product Failed:", {
          status: err.status,
          data: err.body,
          message: err.message,
          fullError: err,
        });

        if (err.status === 422) {
          const body = err.body as { errors?: Record<string, string[]> };
          setFieldErrors(body?.errors ?? {});
        }
      } else {
        console.error(">>> [ERROR] Create Product Failed:", err);
      }
    }
  }

  return (
    <>
      <PageHeader
        title={t("hq.products.new_title")}
        description={t("hq.products.subtitle")}
        backHref={`/hq/${brandSlug}/products`}
      >
        <Button
          type="button"
          variant="outline"
          size="sm"
          className="h-8"
          onClick={handleRequestExit}
          disabled={create.isPending}
        >
          {t("common.cancel")}
        </Button>
        <Button
          type="button"
          size="sm"
          className="h-8 gap-1.5"
          onClick={handleSubmit}
          disabled={!canSubmit}
        >
          {create.isPending ? <Spinner className="size-3.5" /> : <Save className="size-3.5" />}
          {t("hq.products.save")}
        </Button>
      </PageHeader>

      <PageContent>
        <div className="grid grid-cols-1 gap-4 lg:grid-cols-12">
          {/* LEFT: main content */}
          <div className="flex flex-col gap-4 lg:col-span-8">
            <BasicInfoCard
              name={name}
              onNameChange={setName}
              slug={slug}
              onSlugChange={(v) => {
                setSlugTouched(true);
                setSlug(slugify(v));
              }}
              description={description}
              onDescriptionChange={setDescription}
              showBaseSkuPrice
              hasVariants={hasVariants}
              baseSku={baseSku}
              onBaseSkuChange={setBaseSku}
              basePrice={basePrice}
              onBasePriceChange={(v) => {
                setBasePrice(v);
                if (fieldErrors.base_price) {
                  setFieldErrors((prev) => {
                    const next = { ...prev };
                    delete next.base_price;
                    return next;
                  });
                }
              }}
              nameError={fieldErrors["ja.name"]?.[0] ?? fieldErrors.name?.[0]}
              descriptionError={fieldErrors.description?.[0]}
              basePriceError={fieldErrors.base_price?.[0]}
            />

            <Card className="p-4">
              <div className="mb-4 flex items-center justify-between">
                <div className="text-sm font-semibold">{t("hq.products.variants_tab")}</div>
                <Label
                  htmlFor="v-toggle"
                  className="flex cursor-pointer items-center gap-2 text-xs"
                >
                  <Checkbox
                    id="v-toggle"
                    checked={hasVariants}
                    onCheckedChange={(v) => {
                      setHasVariants(v === true);
                      if (v !== true) {
                        setOptions([]);
                        setSkus([]);
                      }
                    }}
                  />
                  {t("hq.products.has_variants")}
                </Label>
              </div>

              {hasVariants && (
                <div className="flex flex-col gap-6">
                  <div className="space-y-3">
                    <div className="text-xs font-medium tracking-tight text-muted-foreground uppercase">
                      {t("hq.products.configure_attributes")}
                    </div>
                    <ProductOptionsBuilder options={options} onChange={setOptions} />
                  </div>

                  <div className="space-y-3 border-t border-dashed pt-4">
                    <div className="text-xs font-medium tracking-tight text-muted-foreground uppercase">
                      {t("hq.products.sku_list")}
                    </div>
                    <ProductSkuPreviewTable options={options} skus={skus} onChange={setSkus} />
                    {missingPriceCount > 0 && (
                      <p
                        role="alert"
                        className="rounded-md border border-destructive/40 bg-destructive/10 px-3 py-2 text-xs font-medium text-destructive"
                      >
                        {t("hq.products.price_required", { n: missingPriceCount })}
                      </p>
                    )}
                  </div>
                </div>
              )}
            </Card>
          </div>

          {/* RIGHT: gallery + sidebar */}
          <div className="flex flex-col gap-4 lg:col-span-4">
            <ProductGalleryCard initialImages={[]} onImagesChange={setGalleryImages} />
            <ProductSidebar
              mode="create"
              status={status}
              isHidden={isHidden}
              onIsHiddenChange={setIsHidden}
              productTypeId={productTypeId}
              onProductTypeIdChange={setProductTypeId}
              productTypes={productTypes.data?.data ?? []}
              productTypesLoading={productTypes.isLoading}
              categoryIds={categoryIds}
              onCategoryIdsChange={setCategoryIds}
              categories={categories.data?.data ?? []}
              categoriesLoading={categories.isLoading}
              taxTypeId={taxTypeId}
              onTaxTypeIdChange={setTaxTypeId}
              taxTypes={taxTypes.data?.data ?? []}
              taxTypesLoading={taxTypes.isLoading}
              taxTypeError={fieldErrors.tax_type_id?.[0]}
              productTypeError={fieldErrors.product_type_id?.[0]}
              showStatus={false}
            />
            <ToppingGroupsPickerCard
              brandSlug={brandSlug}
              groups={toppingGroups.data?.data ?? []}
              loading={toppingGroups.isLoading}
              error={toppingGroups.error}
              selectedIds={toppingGroupIds}
              onChange={setToppingGroupIds}
            />
            <Card className="p-4">
              <div className="mb-3 text-sm font-semibold">
                {t("hq.products.sidebar.publish_status")}
              </div>
              <ProductStatusBadge status={status} variant="panel" />
              <div className="mt-2 border-t pt-2">
                <Label
                  htmlFor="product-hidden-toggle"
                  className="flex w-full cursor-pointer items-center justify-between gap-2 text-xs"
                >
                  <span className="text-muted-foreground">
                    {t("hq.products.sidebar.hide_from_menu")}
                  </span>
                  <Checkbox
                    id="product-hidden-toggle"
                    checked={isHidden}
                    onCheckedChange={(v) => setIsHidden(v === true)}
                  />
                </Label>
              </div>
            </Card>
          </div>
        </div>
      </PageContent>

      {/* Unsaved-changes confirmation */}
      <AlertDialog open={confirmExitOpen} onOpenChange={setConfirmExitOpen}>
        <AlertDialogContent>
          <AlertDialogHeader>
            <AlertDialogTitle>{t("hq.products.unsaved.title")}</AlertDialogTitle>
            <AlertDialogDescription>{t("hq.products.unsaved.desc")}</AlertDialogDescription>
          </AlertDialogHeader>
          <AlertDialogFooter>
            <AlertDialogCancel disabled={create.isPending}>
              {t("hq.products.unsaved.continue_editing")}
            </AlertDialogCancel>
            <Button
              type="button"
              variant="outline"
              size="sm"
              onClick={() => {
                setConfirmExitOpen(false);
                router.push(`/hq/${brandSlug}/products`);
              }}
              disabled={create.isPending}
            >
              {t("hq.products.unsaved.exit_without_saving")}
            </Button>
            <AlertDialogAction
              onClick={(e) => {
                e.preventDefault();
                void handleSubmit();
              }}
              disabled={!canSubmit}
            >
              {create.isPending ? (
                <Spinner className="mr-1.5 size-3.5" />
              ) : (
                <Save className="mr-1.5 size-3.5" />
              )}
              {t("hq.products.unsaved.save_product")}
            </AlertDialogAction>
          </AlertDialogFooter>
        </AlertDialogContent>
      </AlertDialog>
    </>
  );
}

interface ToppingGroupOption {
  id: string;
  name: string;
  /** From the lookup endpoint. Drives the empty-group warning icon —
   *  attaching a group with 0 items to a product is a config mistake. */
  items_count?: number;
}

interface ToppingGroupsPickerCardProps {
  brandSlug: string;
  groups: ToppingGroupOption[];
  loading: boolean;
  error: Error | null;
  selectedIds: string[];
  onChange: (ids: string[]) => void;
}

/**
 * Inline topping-group picker for the combo create flow. Mirrors the popover
 * pattern of the edit-page ProductToppingGroupsCard but is fully controlled —
 * the parent owns the id list and flushes it via toppingGroupService after
 * the product is created. No internal save button, no server fetch.
 */
function ToppingGroupsPickerCard({
  brandSlug,
  groups,
  loading,
  error,
  selectedIds,
  onChange,
}: ToppingGroupsPickerCardProps) {
  const { t } = useTranslation();
  const [open, setOpen] = useState(false);
  // Inline create flow: opens the shared CreateToppingGroupDialog without
  // leaving the combo page. On success the new group is auto-added to
  // selectedIds and cached locally by id→name.
  //
  // Why cache locally: backend `/topping-groups/lookup` filters to
  // `is_active = true` only (ToppingGroupService.php:128). The dialog defaults
  // `is_active: false`, so a freshly-created inactive group never shows up in
  // the lookup refetch — the badge falls back to the raw uuid. Caching the
  // name returned by the create response keeps the badge readable regardless
  // of the active flag, without exposing inactive groups in pickers on other
  // pages (which still rely on the server filter).
  const [createOpen, setCreateOpen] = useState(false);
  const [recentlyCreated, setRecentlyCreated] = useState<Record<string, string>>({});
  const [search, setSearch] = useState("");

  // Merge server lookup with locally-created groups. Locally-created entries
  // always carry items_count: 0 (a freshly-created group is always empty —
  // items are added on the dedicated edit page). Server wins on id collision
  // so admin renames + items_count updates flow through after the next refetch.
  const displayGroups = useMemo(() => {
    const byId = new Map<string, ToppingGroupOption>();
    for (const [id, name] of Object.entries(recentlyCreated)) {
      byId.set(id, { id, name, items_count: 0 });
    }
    for (const g of groups) {
      byId.set(g.id, { ...g, name: g.name ?? `#${g.id.slice(0, 8)}` });
    }
    return Array.from(byId.values());
  }, [groups, recentlyCreated]);

  const optionsById = useMemo(() => {
    const m: Record<string, ToppingGroupOption> = {};
    for (const g of displayGroups) m[g.id] = g;
    return m;
  }, [displayGroups]);

  const selectedGroups = useMemo(
    () => selectedIds.map((id) => optionsById[id] ?? { id, name: id }),
    [selectedIds, optionsById]
  );

  const filteredGroups = useMemo(() => {
    const q = search.trim().toLowerCase();
    if (!q) return displayGroups;
    return displayGroups.filter((g) => g.name.toLowerCase().includes(q));
  }, [displayGroups, search]);

  const showCreate = filteredGroups.length === 0;

  const editGroupHref = useCallback(
    (groupId: string) => `/hq/${brandSlug}/topping-groups/${groupId}`,
    [brandSlug]
  );

  function toggle(id: string) {
    onChange(selectedIds.includes(id) ? selectedIds.filter((x) => x !== id) : [...selectedIds, id]);
  }

  function handleCreated(group: { id: string; name: string }) {
    setRecentlyCreated((prev) => ({ ...prev, [group.id]: group.name }));
    if (!selectedIds.includes(group.id)) {
      onChange([...selectedIds, group.id]);
    }
    // Actionable nudge — newly-created group has 0 items, useless until admin
    // adds toppings. Toast persists until clicked or dismissed (duration 10s)
    // so the admin doesn't miss the next-step CTA.
    toast.info(t("hq.products.combo.empty_after_create"), {
      duration: 10000,
      action: {
        label: t("hq.products.combo.add_toppings_action"),
        onClick: () => window.open(editGroupHref(group.id), "_blank", "noopener,noreferrer"),
      },
    });
  }

  // States: loading → spinner; error → red box; empty → CTA to create groups.
  // The popover-based picker only renders when at least one group exists.
  if (loading) {
    return (
      <Card className="p-4" data-slot="combo-topping-groups-picker">
        <div className="mb-3 text-sm font-semibold">
          {t("hq.topping_groups.product_section.title")}
        </div>
        <div className="flex items-center gap-2 text-xs text-muted-foreground">
          <Spinner className="size-3.5" /> {t("common.loading")}
        </div>
      </Card>
    );
  }

  if (error) {
    return (
      <Card className="p-4" data-slot="combo-topping-groups-picker">
        <div className="mb-3 text-sm font-semibold">
          {t("hq.topping_groups.product_section.title")}
        </div>
        <p
          role="alert"
          className="rounded-md border border-destructive/40 bg-destructive/10 px-3 py-2 text-xs font-medium text-destructive"
        >
          {error.message || t("common.error_loading")}
        </p>
      </Card>
    );
  }

  return (
    <Card className="p-4" data-slot="combo-topping-groups-picker">
      <div className="mb-3 flex items-center justify-between gap-2">
        <div className="text-sm font-semibold">{t("hq.topping_groups.product_section.title")}</div>
        {/* How-to-create-combo: click-toggle popover, sits in the header's
            top-right corner so the hint is discoverable but doesn't take up
            vertical space the way an inline paragraph did. */}
        <Popover>
          <PopoverTrigger asChild>
            <button
              type="button"
              className="flex cursor-pointer items-center gap-1 rounded-sm text-[11px] text-muted-foreground transition-colors hover:text-foreground focus:outline-none focus-visible:ring-2 focus-visible:ring-ring"
            >
              <HelpCircle className="size-3.5" />
              {t("hq.products.combo.how_to_label")}
            </button>
          </PopoverTrigger>
          <PopoverContent side="left" align="start" className="max-w-sm text-xs leading-relaxed">
            <p className="mb-2">{t("hq.products.combo.how_to.intro")}</p>
            <ol className="ml-4 list-decimal space-y-1.5">
              <li>{t("hq.products.combo.how_to.step_1")}</li>
              <li>{t("hq.products.combo.how_to.step_2")}</li>
            </ol>
          </PopoverContent>
        </Popover>
      </div>

      <TooltipProvider delayDuration={150}>
        <Popover
          open={open}
          onOpenChange={(v) => {
            setOpen(v);
            if (!v) setSearch("");
          }}
        >
          <PopoverTrigger asChild>
            <div
              role="combobox"
              aria-expanded={open}
              aria-disabled={loading}
              tabIndex={loading ? -1 : 0}
              onClick={() => !loading && setOpen((v) => !v)}
              onKeyDown={(e) => {
                if ((e.key === "Enter" || e.key === " ") && !loading) {
                  e.preventDefault();
                  setOpen((v) => !v);
                }
              }}
              className={cn(
                "flex min-h-9 w-full cursor-pointer items-start rounded-md border border-input bg-background px-2 py-1.5 text-sm shadow-xs ring-offset-background select-none",
                "focus-visible:ring-2 focus-visible:ring-ring focus-visible:ring-offset-2 focus-visible:outline-none",
                open && "ring-2 ring-ring ring-offset-2",
                loading && "cursor-not-allowed opacity-50"
              )}
            >
              <div className="flex flex-1 flex-wrap gap-1">
                {selectedGroups.length === 0 ? (
                  <span className="px-0.5 text-xs text-muted-foreground">
                    {t("hq.topping_groups.product_section.add_placeholder")}
                  </span>
                ) : (
                  selectedGroups.map((g) => {
                    const isEmpty = (g.items_count ?? 0) === 0;
                    return (
                      <Badge
                        key={g.id}
                        variant="secondary"
                        className={cn(
                          "gap-1 px-1.5 py-0.5 text-xs font-normal",
                          isEmpty && "border border-amber-300 bg-amber-50 text-amber-900"
                        )}
                      >
                        {isEmpty && (
                          <Tooltip>
                            <TooltipTrigger asChild>
                              <span
                                role="button"
                                tabIndex={0}
                                aria-label={t("hq.products.combo.empty_warning")}
                                onClick={(e) => {
                                  e.stopPropagation();
                                  window.open(editGroupHref(g.id), "_blank", "noopener,noreferrer");
                                }}
                                onKeyDown={(e) => {
                                  if (e.key === "Enter" || e.key === " ") {
                                    e.preventDefault();
                                    e.stopPropagation();
                                    window.open(
                                      editGroupHref(g.id),
                                      "_blank",
                                      "noopener,noreferrer"
                                    );
                                  }
                                }}
                                className="flex cursor-pointer items-center"
                              >
                                <AlertTriangle className="size-3 text-amber-600" />
                              </span>
                            </TooltipTrigger>
                            <TooltipContent side="top">
                              {t("hq.products.combo.empty_warning")}
                            </TooltipContent>
                          </Tooltip>
                        )}
                        {g.name}
                        <span
                          role="button"
                          tabIndex={0}
                          aria-label={`Remove ${g.name}`}
                          onClick={(e) => {
                            e.stopPropagation();
                            toggle(g.id);
                          }}
                          onKeyDown={(e) => {
                            if (e.key === "Enter" || e.key === " ") {
                              e.preventDefault();
                              e.stopPropagation();
                              toggle(g.id);
                            }
                          }}
                          className="flex size-3.5 cursor-pointer items-center justify-center rounded-sm hover:bg-muted-foreground/20"
                        >
                          <X className="size-3" />
                        </span>
                      </Badge>
                    );
                  })
                )}
              </div>
              <ChevronsUpDown className="mt-0.5 ml-2 size-4 shrink-0 opacity-50" />
            </div>
          </PopoverTrigger>
          <PopoverContent className="w-[--radix-popover-trigger-width] p-0" align="start">
            <Command shouldFilter={false}>
              <CommandInput
                placeholder={t("hq.topping_groups.product_section.search_placeholder")}
                value={search}
                onValueChange={setSearch}
              />
              <CommandList>
                <CommandGroup>
                  {filteredGroups.map((g) => {
                    const isSelected = selectedIds.includes(g.id);
                    return (
                      <CommandItem key={g.id} value={g.name} onSelect={() => toggle(g.id)}>
                        <Check
                          className={cn("mr-2 size-4", isSelected ? "opacity-100" : "opacity-0")}
                        />
                        {g.name}
                      </CommandItem>
                    );
                  })}
                </CommandGroup>
                {showCreate && (
                  <>
                    {displayGroups.length > 0 && <CommandSeparator />}
                    <CommandGroup>
                      <CommandItem
                        value="__create__"
                        onSelect={() => {
                          setOpen(false);
                          setCreateOpen(true);
                        }}
                        className="text-primary"
                      >
                        <Plus className="mr-2 size-4" />
                        {t("hq.products.combo.create_group_cta")}
                      </CommandItem>
                    </CommandGroup>
                  </>
                )}
              </CommandList>
            </Command>
          </PopoverContent>
        </Popover>
      </TooltipProvider>

      <CreateToppingGroupDialog
        brandSlug={brandSlug}
        open={createOpen}
        onOpenChange={setCreateOpen}
        onCreated={handleCreated}
      />
    </Card>
  );
}
