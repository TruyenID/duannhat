import { readFileSync, readdirSync, statSync } from "node:fs";
import { join, relative } from "node:path";
import { describe, expect, it } from "vitest";

/**
 * #1189 — project rule: icons, not emoji.
 *
 * customer-web was cleaned first (3fb5142, dc5ecab), admin-web followed in
 * c80a8d2. Nothing stopped the next one from arriving, and emoji creep back the
 * same way they arrived: one `label: "🏭 " + name` at a time, invisible in
 * review because it reads as decoration. This test is the ratchet.
 *
 * Only HAND-WRITTEN files are checked. 215+ files under src/ are Omnify output
 * carrying a `⚠️ DO NOT EDIT THIS FILE! ⚠️` banner; editing them here is undone
 * by the next `npm run omnify:gen`, so that emoji has to be fixed in the
 * omnify-ts generator template, not in this repo.
 */
const GENERATED_MARKER = "DO NOT EDIT THIS FILE";

// Pictographs, dingbats (✓ ✕ ✳), enclosed alphanumerics + regional indicators
// (flag halves), and the variation selector that turns a glyph into an emoji.
// Deliberately NOT included: arrows (→), box drawing (─ ┌), and typographic
// marks, all of which are legitimate in comments and ASCII layout.
const EMOJI = /[\u{1F000}-\u{1FAFF}\u{2600}-\u{27BF}\u{FE0F}]/u;

const SOURCE_EXTENSIONS = [".ts", ".tsx", ".js", ".jsx", ".json"];

function sourceFiles(dir: string, found: string[] = []): string[] {
  for (const entry of readdirSync(dir)) {
    const full = join(dir, entry);
    if (statSync(full).isDirectory()) {
      sourceFiles(full, found);
      continue;
    }
    if (SOURCE_EXTENSIONS.some((extension) => entry.endsWith(extension))) {
      found.push(full);
    }
  }
  return found;
}

describe("no emoji in hand-written UI source (#1189)", () => {
  it("finds no emoji outside Omnify-generated files", () => {
    const root = join(process.cwd(), "src");
    const offenders: string[] = [];

    for (const file of sourceFiles(root)) {
      const contents = readFileSync(file, "utf8");
      if (contents.includes(GENERATED_MARKER)) continue;

      const lines = contents.split("\n");
      lines.forEach((line, index) => {
        const match = EMOJI.exec(line);
        if (match) {
          offenders.push(`${relative(process.cwd(), file)}:${index + 1}  ${match[0]}  ${line.trim().slice(0, 80)}`);
        }
      });
    }

    expect(offenders).toEqual([]);
  });

  it("scans a meaningful number of files — a broken walker must not pass silently", () => {
    // The check above is vacuously green if sourceFiles() returns nothing, so
    // assert the walk actually reaches the tree.
    expect(sourceFiles(join(process.cwd(), "src")).length).toBeGreaterThan(200);
  });
});
